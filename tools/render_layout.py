#!/usr/bin/env python3
"""Render shared layout locally; committed HTML is ready for static hosting."""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re
from string import Template

ROOT = Path(__file__).resolve().parents[1]
MARKER = "  <!-- Shared layout: generated by tools/render_layout.py. -->\n"


def localized_url(url, lang):
    return "/en" + url if lang == "en" and url.startswith("/") else url


def render_pages():
    data = json.loads((ROOT / "site/layout.json").read_text())
    templates = {name: Template((ROOT / f"site/{name}.html.tmpl").read_text().rstrip())
                 for name in ("header", "footer")}
    versions = {asset: hashlib.sha256((ROOT / "assets" / asset).read_bytes()).hexdigest()[:12]
                for asset in ("style.css", "lang.js")}
    company = data["company"]
    results = {}
    for page, navigation in data["pages"].items():
        ko_url = f"/{page}/" if page else "/"
        for lang in ("ko", "en"):
            url = localized_url(ko_url, lang)
            path = ROOT / url.lstrip("/") / "index.html"
            values = {key: html.escape(value) for key, value in data["labels"][lang].items()}
            values.update(
                home_url=localized_url("/", lang),
                privacy_url=localized_url("/privacy/", lang),
                support_url=localized_url("/support/", lang),
                company_name=html.escape(company[lang]),
                registration_number=html.escape(company["registration"]),
                email=html.escape(company["email"]),
                copyright=html.escape(company["copyright"]),
                addresses="\n".join("        " + html.escape(company["address_" + code]) + "<br>"
                                    for code in (("ko", "en") if lang == "ko" else ("en",))),
                nav_links="\n".join(
                    f'        <a href="{html.escape(localized_url(target, lang))}">{values[label]}</a>'
                    for target, label in navigation),
                language_links="\n".join(
                    f'        <a href="{localized_url(ko_url, code)}" data-lang="{code}"'
                    + (' class="active" aria-current="true"' if code == lang else '')
                    + f' lang="{code}">{label}</a>'
                    for code, label in (("ko", "한국어"), ("en", "English"))),
            )
            source = path.read_text()
            for name, template in templates.items():
                pattern = rf'(?:{re.escape(MARKER)})?  <{name} class="site-{name}">.*?</{name}>'
                source, count = re.subn(pattern, lambda _: template.substitute(values), source, flags=re.S)
                if count != 1:
                    raise ValueError(f"{path}: expected one shared {name}, found {count}")
            for asset, version in versions.items():
                pattern = rf'(/assets/{re.escape(asset)})(?:\?[^"\s]*)?"'
                source, count = re.subn(pattern, lambda m: f'{m[1]}?v={version}"', source)
                if count != 1:
                    raise ValueError(f"{path}: expected one reference to {asset}, found {count}")
            results[path] = source
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report stale HTML without writing files")
    args = parser.parse_args()
    pages = render_pages()
    stale = [path for path, source in pages.items() if path.read_text() != source]
    if args.check:
        for path in stale:
            print(f"Stale layout or asset version: {path.relative_to(ROOT)}")
        if not stale:
            print(f"Shared layout and asset versions match on {len(pages)} pages.")
        return int(bool(stale))
    for path in stale:
        path.write_text(pages[path])
    print(f"Updated {len(stale)} of {len(pages)} pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
